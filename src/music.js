export function themeStep(id, index) {
  const theme = THEMES[id];
  if (!theme) return [];
  const step = 60 / theme.bpm / 2,
    notes = [],
    midi = theme.notes[index % theme.notes.length];
  if (midi !== null)
    notes.push({
      frequency: 440 * 2 ** ((midi - 69) / 12),
      duration: step * 0.74,
      type: theme.wave,
      level: theme.wave === "square" ? 0.011 : 0.018,
    });
  if (index % 4 === 0) {
    const bass = theme.bass[Math.floor(index / 4) % theme.bass.length];
    notes.push({
      frequency: 440 * 2 ** ((bass - 69) / 12),
      duration: step * 2.8,
      type: "triangle",
      level: 0.018,
    });
  }
  return notes;
}
